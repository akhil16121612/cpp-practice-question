#include <iostream>
#include <algorithm>
#include <cmath>
#include <string>
#include <vector>
using namespace std;

void remove(vector<int>a ,int target ){
    int target();
    vector<int> output;
    for(auto i = 0 ; i < a.size() ; i++){
        if(target != a[i]){
            output.push_back(a[i]);
        }
        
    }
}

int main(){
    vector <int> a = {1,2,3,4,5};
    int target = 4;
    remove(a , target);
    return 0;
    
}